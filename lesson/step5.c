/* 第 5 步：把整个画面存进数组，用循环一行一行画出来 */
#include <stdio.h>
#include <unistd.h>

/* 15 行字符画。每一行都是一个字符串，
   放在函数外面 —— 这叫全局数组，里面所有函数都能看见它。
   （严格做法是把数组当参数传进函数，但那要用指针，第 8 章再讲） */
const char *heart[] = {
    "     *****   *****     ",
    "   *******   *******   ",
    "  *******************  ",
    "***********************",
    " ********************* ",
    "  *******************  ",
    "   *****************   ",
    "    ***************    ",
    "     *************     ",
    "      ***********      ",
    "       *********       ",
    "        *******        ",
    "         *****         ",
    "          ***          ",
    "           *           "
};

void print_heart(int delay_ms)
{
    /* sizeof(heart)     = 整个数组占多少字节 = 15 x 8 = 120
       sizeof(heart[0])  = 一个元素占多少字节 = 8
       相除就得到行数，不用手写 15，以后加行也不会忘改 */
    int n = sizeof(heart) / sizeof(heart[0]);

    for (int i = 0; i < n; i++)
    {
        printf("%s\n", heart[i]);   /* %s 打整个字符串 */
        fflush(stdout);
        usleep(delay_ms * 1000);
    }
}

int main(void)
{
    print_heart(80);
    printf("\n     新  婚  快  乐  \n");
    return 0;
}
