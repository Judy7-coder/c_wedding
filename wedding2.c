/* 版本 2：字符画爱心 + 逐行延时，让程序"长出来" */
#include <stdio.h>
#include <unistd.h>   /* usleep() 在这里，控制延时 */

int main(void)
{
    const char *heart[] = {
        "     *****   *****     ",
        "   *******   *******   ",
        "  *******************  ",
        "***********************",
        " ********************* ",
        "  *******************  ",
        "   *****************   ",
        "    ***************    ",
        "     *************     ",
        "      ***********      ",
        "       *********       ",
        "        *******        ",
        "         *****         ",
        "          ***          ",
        "           *           "
    };

    int lines = sizeof(heart) / sizeof(heart[0]);   /* 数组长度：45/5 = 15 */

    for (int i = 0; i < lines; i++)
    {
        printf("%s\n", heart[i]);
        fflush(stdout);          /* 立刻把缓冲区吐到屏幕，否则会一次性全部出现 */
        usleep(80000);           /* 停 80000 微秒 = 0.08 秒 */
    }

    printf("\n     新  婚  快  乐  \n");
    return 0;
}
